    <p>Балка переменного сечения — это сварная балка, высота стенки которой изменяется по длине. Такое решение позволяет максимально эффективно использовать материал в соответствии с эпюрой изгибающих моментов.</p>

    <h2>Где это применяется?</h2>
    <p>Наиболее часто балки переменного сечения используются в каркасах однопролетных и многопролетных зданий (склады, ангары, производственные цеха). В таких конструкциях максимальный изгибающий момент возникает в местах соединения ригеля с колонной, а к середине пролета он уменьшается. Соответственно, и высота балки делается максимальной у опор и минимальной в середине.</p>

    <h2>Ключевые преимущества</h2>
    <ul>
        <li><b>Экономия металла:</b> Снижение веса конструкции может достигать 20-30% по сравнению с использованием балок постоянного сечения.</li>
        <li><b>Архитектурная выразительность:</b> Конструкции с переменным сечением выглядят более изящно и современно.</li>
        <li><b>Оптимизация пространства:</b> Уменьшение высоты балки в середине пролета может увеличить полезную высоту помещения.</li>
    </ul>

    <h2>Пример</h2>
    <p>Для рамы пролетом 24 метра использование балки постоянного сечения 80Б1 (вес 8.7 тонн) можно заменить на сварную балку переменного сечения с высотой от 500 до 800 мм. Вес такой конструкции составит около 6.5 тонн. <strong>Экономия — более 2 тонн металла на одну раму!</strong></p>

