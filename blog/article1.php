    <p>Оптимизация металлоемкости — один из ключевых факторов снижения стоимости строительных конструкций. Сварные балки, в отличие от прокатных, позволяют гибко подбирать сечение, что ведет к значительной экономии материала. Давайте разберемся, как это работает.</p>

    <h2>Формула расчета веса</h2>
    <p>Вес одного погонного метра (п.м.) двутавровой балки рассчитывается по формуле:</p>
    <p><code>Масса (кг/м) = ( (H - 2*t)*s + 2*B*t ) * 7850 / 1 000 000</code></p>
    <p>Где:</p>
    <ul>
        <li><b>H</b> – высота балки, мм</li>
        <li><b>B</b> – ширина полки, мм</li>
        <li><b>s</b> – толщина стенки, мм</li>
        <li><b>t</b> – толщина полки, мм</li>
        <li><b>7850</b> – плотность стали, кг/м³</li>
    </ul>

    <h2>Пример экономии</h2>
    <p>Предположим, для проекта требуется балка с моментом сопротивления Wx = 1500 см³. В сортаменте прокатных балок ближайшим аналогом будет 50Б1 (ГОСТ 8239-89) с Wx = 1550 см³ и весом 57.8 кг/м.</p>
    <p>Мы можем спроектировать сварную балку с теми же характеристиками, но с оптимизированными параметрами (например, высота 500 мм, ширина полки 200 мм, толщина стенки 8 мм, толщина полки 12 мм). Ее вес составит всего 56 кг/м. Экономия на одном метре — 1.8 кг, что на больших объемах выливается в тонны сэкономленного металла и десятки тысяч рублей.</p>

